export const STRINGS: Record<Lang, Record<StringKey, string>> = { fr, en, ht };

/** Texte traduit, avec remplacement des paramètres `{nom}`. */
export function t(lang: Lang, key: StringKey, params: Record<string, string | number> = {}): string {
  return STRINGS[lang][key].replace(/\{(\w+)\}/g, (_, k: string) => (k in params ? String(params[k]) : `{${k}}`));
}

